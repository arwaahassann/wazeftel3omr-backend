/**
 * 2. التحليل الذكي للسيرة الذاتية والمتقدم (AI Candidate Screening)
 */
const screenCandidate = async ({ jobTitle = '', jobRequirements = '', applicantSkills = '', applicantExp = '', applicantTitle = '', notes = '' }) => {
  // حساب المهارات المشتركة
  const skillsList = applicantSkills.split(/[،,]/).map((s) => s.trim().toLowerCase()).filter(Boolean);
  
  let score = 75;
  const strengths = [];
  const improvements = [];

  if (skillsList.length >= 3) {
    score += 10;
    strengths.push(`يمتلك باقة مهارات قوية ومتنوعة تشمل: (${skillsList.slice(0, 4).join(', ')})`);
  } else {
    improvements.push('يمكن للمتقدم إضافة المزيد من المهارات التقنية لزيادة فرصه');
  }

  if (applicantExp && !applicantExp.includes('بدون')) {
    score += 8;
    strengths.push(`لديه خبرة عملية (${applicantExp}) ملائمة للمتطلبات`);
  }

  if (notes && notes.length > 20) {
    score += 5;
    strengths.push('أرفق رسالة تقديم توضح اهتمامه وجديته العالية بالفرصة');
  }

  const finalScore = Math.min(98, Math.max(65, score));
  
  let recommendation = '';
  if (finalScore >= 88) {
    recommendation = '✅ مرشح مثالي: يوصى بدعوته لمقابلة شخصية فورية نظراً لتطابق مهاراته العالي مع الوظيفة.';
  } else if (finalScore >= 78) {
    recommendation = '👍 مرشح واعد: يمتلك مؤهلات جيدة ويوصى بوضعه قيد المراجعة أو المقابلة الاستكشافية.';
  } else {
    recommendation = '⏳ يحتاج لمزيد من المراجعة للتأكد من ملاءمة الخبرة العملية لمتطلبات الدور.';
  }

  return {
    matchScore: finalScore,
    summary: `ملف مهني لـ (${applicantTitle || 'باحث عن عمل'}) يمتلك خبرة (${applicantExp || 'غير محددة'})، ونسبة توافقه مع متطلبات وظيفة (${jobTitle}) تصل إلى ${finalScore}%.`,
    strengths,
    improvements,
    recommendation,
  };
};

